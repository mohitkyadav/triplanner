// Regenerates src/lib/airlines-data.js (IATA code → airline name) from the
// OpenFlights airline database. Run manually when the data feels stale:
//
//   node scripts/gen-airlines.mjs
//
// The output is committed so the app needs no network or API for names.
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE = 'https://raw.githubusercontent.com/jpatokal/openflights/master/data/airlines.dat'

// OpenFlights hasn't tracked every rebrand/launch — patched by hand here.
const OVERRIDES = {
  AZ: 'ITA Airways',
  QP: 'Akasa Air',
  RX: 'Riyadh Air',
  N0: 'Norse Atlantic Airways',
  W4: 'Wizz Air Malta',
  W9: 'Wizz Air UK',
  TP: 'TAP Air Portugal',
  SK: 'Scandinavian Airlines',
  '6E': 'IndiGo',
  LA: 'LATAM Airlines',
}

// Minimal CSV line parser (handles quoted fields with commas).
function parseLine(line) {
  const fields = []
  let cur = ''
  let inQuotes = false
  for (let i = 0; i < line.length; i++) {
    const ch = line[i]
    if (inQuotes) {
      if (ch === '"' && line[i + 1] === '"') {
        cur += '"'
        i++
      } else if (ch === '"') inQuotes = false
      else cur += ch
    } else if (ch === '"') inQuotes = true
    else if (ch === ',') {
      fields.push(cur)
      cur = ''
    } else cur += ch
  }
  fields.push(cur)
  return fields
}

const text = await (await fetch(SOURCE)).text()
const byIata = new Map()
let rows = 0

for (const line of text.split('\n')) {
  if (!line.trim()) continue
  rows++
  const f = parseLine(line)
  const [id, name, , iata, , , , active] = f
  if (active !== 'Y') continue
  if (!/^[A-Z0-9]{2}$/.test(iata) || /^\d{2}$/.test(iata)) continue
  if (!name || name === 'Unknown' || name === 'Private flight' || name === '\\N') continue
  // junk user submissions ("Zz", names that are just the code itself)
  if (name.length < 3 || name.toLowerCase() === iata.toLowerCase()) continue
  const prev = byIata.get(iata)
  // Duplicate active codes are usually a cargo/regional subsidiary sharing the
  // parent's code: prefer the non-cargo name, then the older (original) entry.
  const cargo = /cargo/i.test(name)
  const better =
    !prev || (prev.cargo && !cargo) || (prev.cargo === cargo && Number(id) < prev.id)
  if (better) byIata.set(iata, { id: Number(id), name, cargo })
}

const map = {}
for (const [iata, { name }] of [...byIata.entries()].sort()) map[iata] = name
Object.assign(map, OVERRIDES)

const out = `// Generated by scripts/gen-airlines.mjs — do not edit by hand.
// Source: OpenFlights airline database (https://openflights.org/data), ODbL.
// ${Object.keys(map).length} active airlines with IATA codes.
export const AIRLINES = ${JSON.stringify(map, null, 0)}
`
const dest = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/airlines-data.js')
writeFileSync(dest, out)
console.log(`parsed ${rows} rows → ${Object.keys(map).length} airlines → ${dest} (${(out.length / 1024).toFixed(1)} KB)`)
